export type IconName = keyof typeof icons

/** An icon as text in the icon font; decorative unless given a label. */
export function icon(name: IconName, label?: string): string {
  const glyph = `&#x${icons[name].toString(16)};`
  return label == null
    ? `<span class="icon" aria-hidden="true">${glyph}</span>`
    : `<span class="icon" role="img" aria-label="${label.replace(/[&<>"']/g, '')}">${glyph}</span>`
}
